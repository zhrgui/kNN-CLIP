"""
Build or extend the kNN-CLIP retrieval database in a single pass (Sec. 3.1 of
the paper).

DINOv2 features of each image are mask-average-pooled once per annotated class
(Eq. 1). Only the L2-normalised embeddings and their labels are kept, so no
image has to be stored to grow the database later with --append.

Labels are the pixel values of the annotation maps. They must index the
vocabulary of the dataset being evaluated, as the maps generated by
datasets/prepare_*.py do.
"""

import argparse
import os

import cv2
import faiss
import numpy as np
import torch
from PIL import Image
from tqdm import tqdm

from fcclip.modeling.retrieval_classification.dinov2_feature_extraction import (
    DINOV2_FEAT_DIM,
    build_dinov2,
    extract_feature_maps,
    preprocess_image,
)
from fcclip.modeling.retrieval_classification.faiss_search import (
    INDEX_FILENAME,
    LABELS_FILENAME,
)

IMAGE_EXTENSIONS = (".jpg", ".jpeg", ".png")
# Annotation file types and their ignore values, see fcclip/data/datasets/.
IGNORE_LABELS = {".png": 255, ".tif": 65535}


def get_parser():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--img_dir", required=True, help="training images")
    parser.add_argument(
        "--mask_dir",
        required=True,
        help="annotation maps named like the images, with one class id per pixel",
    )
    parser.add_argument(
        "--out_dir", required=True, help="database directory to write"
    )
    parser.add_argument(
        "--append",
        action="store_true",
        help="add to the database in --out_dir instead of creating a new one",
    )
    parser.add_argument("--image_size", type=int, default=518)
    parser.add_argument(
        "--dinov2_weights",
        default="",
        help="path or URL of the DINOv2 weights, empty for the official ones",
    )
    parser.add_argument(
        "--index_type",
        choices=["flat", "hnsw"],
        default="flat",
        help="exact search, or approximate search that is faster on large databases",
    )
    parser.add_argument("--hnsw_m", type=int, default=32)
    parser.add_argument("--ef_construction", type=int, default=100)
    parser.add_argument("--ef_search", type=int, default=64)
    parser.add_argument("--cpu", action="store_true", help="run DINOv2 on CPU")
    return parser


def create_index(args):
    if args.index_type == "flat":
        return faiss.IndexFlatIP(DINOV2_FEAT_DIM)
    # The metric must be given explicitly: FAISS defaults to L2 for HNSW.
    index = faiss.IndexHNSWFlat(
        DINOV2_FEAT_DIM, args.hnsw_m, faiss.METRIC_INNER_PRODUCT
    )
    index.hnsw.efConstruction = args.ef_construction
    index.hnsw.efSearch = args.ef_search
    return index


def find_mask(mask_dir, image_name):
    stem = os.path.splitext(image_name)[0]
    for extension in IGNORE_LABELS:
        mask_path = os.path.join(mask_dir, stem + extension)
        if os.path.exists(mask_path):
            return mask_path, IGNORE_LABELS[extension]
    return None, None


def pool_embeddings(feature_map, mask, ignore_label):
    """
    Mask-average-pool a [C, H, W] feature map once per class in the annotation
    map, skipping classes too small to cover a patch at this resolution.
    """
    height, width = feature_map.shape[-2:]
    embeddings, labels = [], []
    for category in np.unique(mask):
        if category == ignore_label:
            continue
        binary_mask = cv2.resize(
            (mask == category).astype(np.uint8),
            (width, height),
            interpolation=cv2.INTER_NEAREST,
        )
        area = int(binary_mask.sum())
        if area == 0:
            continue
        embedding = (feature_map * binary_mask).sum(axis=(-1, -2)) / area
        embeddings.append(embedding / (np.linalg.norm(embedding) + 1e-8))
        labels.append(int(category))
    return embeddings, labels


def main(args):
    os.makedirs(args.out_dir, exist_ok=True)
    index_path = os.path.join(args.out_dir, INDEX_FILENAME)
    labels_path = os.path.join(args.out_dir, LABELS_FILENAME)
    if args.append:
        index = faiss.read_index(index_path)
        all_labels = np.load(labels_path)["idx_to_class"].tolist()
    else:
        index = create_index(args)
        all_labels = []

    device = "cpu" if args.cpu else "cuda"
    extractor = build_dinov2(args.dinov2_weights).to(device)

    image_names = sorted(
        name
        for name in os.listdir(args.img_dir)
        if name.lower().endswith(IMAGE_EXTENSIONS)
    )
    all_embeddings = []
    num_without_mask = 0
    for image_name in tqdm(image_names, desc="Building database"):
        mask_path, ignore_label = find_mask(args.mask_dir, image_name)
        if mask_path is None:
            num_without_mask += 1
            continue
        image = Image.open(os.path.join(args.img_dir, image_name)).convert(
            "RGB"
        )
        image = (
            preprocess_image(image, args.image_size).unsqueeze(0).to(device)
        )
        with torch.no_grad():
            feature_map = (
                extract_feature_maps(extractor, image)[0].cpu().numpy()
            )
        embeddings, labels = pool_embeddings(
            feature_map, np.array(Image.open(mask_path)), ignore_label
        )
        all_embeddings.extend(embeddings)
        all_labels.extend(labels)

    if not all_embeddings:
        raise ValueError(
            f"No embeddings: found no annotated images in {args.img_dir} with "
            f"masks in {args.mask_dir}."
        )
    index.add(np.stack(all_embeddings).astype(np.float32))
    faiss.write_index(index, index_path)
    np.savez(labels_path, idx_to_class=np.array(all_labels))
    print(
        f"{args.out_dir}: added {len(all_embeddings)} embeddings from "
        f"{len(image_names) - num_without_mask} images "
        f"({num_without_mask} images had no mask). The database now has "
        f"{index.ntotal} embeddings and {len(set(all_labels))} classes."
    )


if __name__ == "__main__":
    main(get_parser().parse_args())
